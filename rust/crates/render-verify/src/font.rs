//! A 5×7 bitmap font for labelling sheets: upper-case letters, digits and a
//! little punctuation. Lower case is drawn upper case; anything else as `?`.

use crate::image::Image;

/// Glyph rows top to bottom, five bits each, the leftmost pixel highest.
fn glyph(c: char) -> [u8; 7] {
    match c.to_ascii_uppercase() {
        'A' => [0x0E, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11],
        'B' => [0x1E, 0x11, 0x11, 0x1E, 0x11, 0x11, 0x1E],
        'C' => [0x0E, 0x11, 0x10, 0x10, 0x10, 0x11, 0x0E],
        'D' => [0x1C, 0x12, 0x11, 0x11, 0x11, 0x12, 0x1C],
        'E' => [0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x1F],
        'F' => [0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x10],
        'G' => [0x0E, 0x11, 0x10, 0x17, 0x11, 0x11, 0x0F],
        'H' => [0x11, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11],
        'I' => [0x0E, 0x04, 0x04, 0x04, 0x04, 0x04, 0x0E],
        'J' => [0x07, 0x02, 0x02, 0x02, 0x02, 0x12, 0x0C],
        'K' => [0x11, 0x12, 0x14, 0x18, 0x14, 0x12, 0x11],
        'L' => [0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x1F],
        'M' => [0x11, 0x1B, 0x15, 0x15, 0x11, 0x11, 0x11],
        'N' => [0x11, 0x11, 0x19, 0x15, 0x13, 0x11, 0x11],
        'O' => [0x0E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E],
        'P' => [0x1E, 0x11, 0x11, 0x1E, 0x10, 0x10, 0x10],
        'Q' => [0x0E, 0x11, 0x11, 0x11, 0x15, 0x12, 0x0D],
        'R' => [0x1E, 0x11, 0x11, 0x1E, 0x14, 0x12, 0x11],
        'S' => [0x0F, 0x10, 0x10, 0x0E, 0x01, 0x01, 0x1E],
        'T' => [0x1F, 0x04, 0x04, 0x04, 0x04, 0x04, 0x04],
        'U' => [0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E],
        'V' => [0x11, 0x11, 0x11, 0x11, 0x11, 0x0A, 0x04],
        'W' => [0x11, 0x11, 0x11, 0x15, 0x15, 0x15, 0x0A],
        'X' | '×' => [0x11, 0x11, 0x0A, 0x04, 0x0A, 0x11, 0x11],
        'Y' => [0x11, 0x11, 0x0A, 0x04, 0x04, 0x04, 0x04],
        'Z' => [0x1F, 0x01, 0x02, 0x04, 0x08, 0x10, 0x1F],
        '0' => [0x0E, 0x11, 0x13, 0x15, 0x19, 0x11, 0x0E],
        '1' => [0x04, 0x0C, 0x04, 0x04, 0x04, 0x04, 0x0E],
        '2' => [0x0E, 0x11, 0x01, 0x02, 0x04, 0x08, 0x1F],
        '3' => [0x1F, 0x02, 0x04, 0x02, 0x01, 0x11, 0x0E],
        '4' => [0x02, 0x06, 0x0A, 0x12, 0x1F, 0x02, 0x02],
        '5' => [0x1F, 0x10, 0x1E, 0x01, 0x01, 0x11, 0x0E],
        '6' => [0x06, 0x08, 0x10, 0x1E, 0x11, 0x11, 0x0E],
        '7' => [0x1F, 0x01, 0x02, 0x04, 0x08, 0x08, 0x08],
        '8' => [0x0E, 0x11, 0x11, 0x0E, 0x11, 0x11, 0x0E],
        '9' => [0x0E, 0x11, 0x11, 0x0F, 0x01, 0x02, 0x0C],
        ' ' => [0; 7],
        '.' | '·' => [0, 0, 0, 0, 0, 0x0C, 0x0C],
        ',' => [0, 0, 0, 0, 0x0C, 0x04, 0x08],
        ':' => [0, 0x0C, 0x0C, 0, 0x0C, 0x0C, 0],
        '+' => [0, 0x04, 0x04, 0x1F, 0x04, 0x04, 0],
        '-' | '−' | '–' => [0, 0, 0, 0x1F, 0, 0, 0],
        '%' => [0x18, 0x19, 0x02, 0x04, 0x08, 0x13, 0x03],
        '/' => [0, 0x01, 0x02, 0x04, 0x08, 0x10, 0],
        '(' => [0x02, 0x04, 0x08, 0x08, 0x08, 0x04, 0x02],
        ')' => [0x08, 0x04, 0x02, 0x02, 0x02, 0x04, 0x08],
        '=' => [0, 0, 0x1F, 0, 0x1F, 0, 0],
        _ => [0x0E, 0x11, 0x01, 0x02, 0x04, 0, 0x04],
    }
}

/// Glyph advance in pixels at scale 1.
pub const ADVANCE: u32 = 6;
/// Line height in pixels at scale 1.
pub const LINE: u32 = 9;

/// Draws `text` with its top-left at (x, y), each font pixel `scale` image
/// pixels square, clipped to the image. Returns the width drawn.
pub fn draw_text(
    image: &mut Image,
    x: u32,
    y: u32,
    text: &str,
    scale: u32,
    colour: [u8; 4],
) -> u32 {
    let scale = scale.max(1);
    let mut pen = x;
    for c in text.chars() {
        let rows = glyph(c);
        for (row, bits) in rows.iter().enumerate() {
            for column in 0..5u32 {
                if bits & (0x10 >> column) == 0 {
                    continue;
                }
                for dy in 0..scale {
                    for dx in 0..scale {
                        let (px, py) = (pen + column * scale + dx, y + row as u32 * scale + dy);
                        if px < image.width && py < image.height {
                            image.set_pixel(px, py, colour);
                        }
                    }
                }
            }
        }
        pen += ADVANCE * scale;
    }
    pen - x
}

/// The width `text` takes at `scale`.
pub fn text_width(text: &str, scale: u32) -> u32 {
    text.chars().count() as u32 * ADVANCE * scale.max(1)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn text_draws_within_its_measured_width() {
        let mut image = Image::new(80, 20, [0, 0, 0, 255]);
        let width = draw_text(&mut image, 2, 2, "AO +0.2%", 1, [255, 255, 255, 255]);
        assert_eq!(width, text_width("AO +0.2%", 1));
        let lit: usize = image
            .rgba
            .as_chunks::<4>()
            .0
            .iter()
            .filter(|pixel| pixel[0] == 255)
            .count();
        assert!(lit > 20);
        // Nothing beyond the text's box.
        for y in 0..20 {
            for x in (2 + width)..80 {
                assert_eq!(image.pixel(x, y)[0], 0);
            }
        }
    }

    #[test]
    fn lower_case_draws_as_upper_case_and_unknown_as_a_question_mark() {
        assert_eq!(glyph('a'), glyph('A'));
        assert_eq!(glyph('~'), glyph('?'));
    }
}

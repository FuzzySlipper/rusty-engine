                {
                    ProductInputEvent[] events = new ProductInputEvent[checked((int)count)];
                    for (nuint index = 0; index < count; index++)
                    {
                        NativeInputEvent input = source[index];
                        events[checked((int)index)] = new ProductInputEvent(

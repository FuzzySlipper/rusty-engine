using System;
using System.IO;
using Microsoft.CodeAnalysis;

namespace Rusty.Engine.ProductGenerator;

[Generator]
public sealed class ProductGenerator : IIncrementalGenerator
{
    private const string ProductAttribute = "Rusty.Engine.EngineProductAttribute";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(static output =>
        {
            output.AddSource("Interop.g.cs", SourceText("Rusty.Engine.ProductGenerator.GeneratedInputs.Interop.g.cs"));
            output.AddSource("EngineServiceImplementations.g.cs", SourceText("Rusty.Engine.ProductGenerator.GeneratedInputs.EngineServiceImplementations.g.cs"));
        });

        context.RegisterSourceOutput(context.CompilationProvider, static (output, compilation) =>
        {
            INamedTypeSymbol[] candidates = compilation.Assembly.GetAttributes()
                .Where(attribute => attribute.AttributeClass?.ToDisplayString() == ProductAttribute)
                .Select(ProductType)
                .Where(product => product is not null)
                .Cast<INamedTypeSymbol>()
                .ToArray();
            if (candidates.Length != 1)
            {
                output.ReportDiagnostic(Diagnostic.Create(
                    new DiagnosticDescriptor("RUSTY001", "One NativeProduct selection is required", "Select exactly one product with [assembly: EngineProduct(typeof(...))]", "Rusty.Engine", DiagnosticSeverity.Error, true),
                    Location.None));
                return;
            }

            INamedTypeSymbol product = candidates[0];
            output.AddSource("ProductExports.g.cs", Exports(product));
        });
    }

    private static INamedTypeSymbol? ProductType(AttributeData attribute)
    {
        if (attribute.ConstructorArguments.Length != 1)
        {
            return null;
        }
        return attribute.ConstructorArguments[0].Value as INamedTypeSymbol;
    }

    private static string SourceText(string resourceName)
    {
        using Stream stream = typeof(ProductGenerator).Assembly.GetManifestResourceStream(resourceName)
            ?? throw new InvalidOperationException($"Missing embedded generator input {resourceName}.");
        using StreamReader reader = new(stream);
        return reader.ReadToEnd();
    }

    private static string Exports(INamedTypeSymbol product)
    {
        string type = product.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        return $$"""
            // <auto-generated />
            #nullable enable
            using System;
            using System.Runtime.CompilerServices;
            using System.Runtime.InteropServices;
            using Rusty.Engine;

            namespace Rusty.Engine.NativeProduct;

            internal sealed class EngineContext : IEngineContext
            {
                internal EngineContext(NativeEngineApi native)
                {
                    Look = new LookServiceImplementation(native.look);
                    Spatial = new SpatialServiceImplementation(native.spatial);
                    Appearance = new AppearanceServiceImplementation(native.appearance);
                    Random = new RngServiceImplementation(native.rng);
                    Ui = new UiServiceImplementation(native.ui);
                }

                public ILookService Look { get; }
                public ISpatialService Spatial { get; }
                public IAppearanceService Appearance { get; }
                public IRandomService Random { get; }
                public IUiService Ui { get; }
            }

            internal sealed class ProductLifetime
            {
                private IEngineProduct? _product;
                internal ProductLifetime(IEngineProduct product) => _product = product;
                internal IEngineProduct Product => _product ?? throw new ObjectDisposedException(nameof(ProductLifetime));
                internal void Dispose() => System.Threading.Interlocked.Exchange(ref _product, null)?.Dispose();
            }

            internal static unsafe class ProductExports
            {
                [UnmanagedCallersOnly(EntryPoint = "rusty_product_bind", CallConvs = [typeof(CallConvCdecl)])]
                internal static int Bind(NativeProductApi* api)
                {
                    if (api is null) return 2;
                    api->create = &Create;
                    api->start = &Start;
                    api->turn = &Turn;
                    api->pause = &Pause;
                    api->resume = &Resume;
                    api->shutdown = &Shutdown;
                    api->destroy = &Destroy;
                    return 1;
                }

                [UnmanagedCallersOnly(CallConvs = [typeof(CallConvCdecl)])]
                private static int Create(NativeProductCreateArgs* args, void** handle)
                {
                    ProductLifetime? lifetime = null;
                    try
                    {
                        if (args is null || handle is null || (args->content_len != 0 && args->content is null)) return 2;
                        ProductContent content = new(CopyContent(args->content, args->content_len));
                        IEngineProduct product = new {{type}}(new ProductCreateContext(new EngineContext(args->engine), content));
                        lifetime = new ProductLifetime(product);
                        *handle = (void*)GCHandle.ToIntPtr(GCHandle.Alloc(lifetime));
                        return 1;
                    }
                    catch
                    {
                        try { lifetime?.Dispose(); }
                        catch { }
                        return 99;
                    }
                }

                [UnmanagedCallersOnly(CallConvs = [typeof(CallConvCdecl)])]
                private static int Start(void* handle) => Invoke(handle, static product => product.Start());

                [UnmanagedCallersOnly(CallConvs = [typeof(CallConvCdecl)])]
                private static int Turn(void* handle, NativeTurnArgs* args)
                {
                    try
                    {
                        if (args is null || (args->event_count != 0 && args->events is null)) return 2;
                        Get(handle).Product.Update(new ProductUpdate(args->kind, CopyInput(args->events, args->event_count), args->observed_time_or_step));
                        return 1;
                    }
                    catch { return 99; }
                }

                [UnmanagedCallersOnly(CallConvs = [typeof(CallConvCdecl)])]
                private static int Pause(void* handle) => Invoke(handle, static product => product.Pause());

                [UnmanagedCallersOnly(CallConvs = [typeof(CallConvCdecl)])]
                private static int Resume(void* handle) => Invoke(handle, static product => product.Resume());

                [UnmanagedCallersOnly(CallConvs = [typeof(CallConvCdecl)])]
                private static int Shutdown(void* handle) => Invoke(handle, static product => product.Shutdown());

                [UnmanagedCallersOnly(CallConvs = [typeof(CallConvCdecl)])]
                private static void Destroy(void* handle)
                {
                    if (handle is null) return;
                    GCHandle reference = GCHandle.FromIntPtr((nint)handle);
                    try
                    {
                        if (reference.Target is ProductLifetime lifetime) lifetime.Dispose();
                    }
                    catch { }
                    finally
                    {
                        try { reference.Free(); }
                        catch { }
                    }
                }

                private static int Invoke(void* handle, Action<IEngineProduct> action)
                {
                    try { action(Get(handle).Product); return 1; }
                    catch { return 99; }
                }

                private static ProductLifetime Get(void* handle)
                {
                    if (handle is null) throw new ArgumentNullException(nameof(handle));
                    return (ProductLifetime)GCHandle.FromIntPtr((nint)handle).Target!;
                }

                private static ProductContentFile[] CopyContent(NativeContentFile* source, nuint count)
                {
                    ProductContentFile[] files = new ProductContentFile[checked((int)count)];
                    for (nuint index = 0; index < count; index++)
                    {
                        NativeContentFile file = source[index];
                        files[checked((int)index)] = new ProductContentFile(CopyBytes(file.path, file.path_len), CopyBytes(file.bytes, file.bytes_len));
                    }
                    return files;
                }

                private static ProductInputEvent[] CopyInput(NativeInputEvent* source, nuint count)
                {
                    ProductInputEvent[] events = new ProductInputEvent[checked((int)count)];
                    for (nuint index = 0; index < count; index++)
                    {
                        NativeInputEvent input = source[index];
                        events[checked((int)index)] = new ProductInputEvent(input.kind, input.edge, input.sequence, input.x, input.y, CopyBytes(input.label, input.label_len));
                    }
                    return events;
                }

                private static ReadOnlyMemory<byte> CopyBytes(byte* source, nuint length)
                {
                    if (length == 0) return ReadOnlyMemory<byte>.Empty;
                    if (source is null) throw new ArgumentException("nonempty native byte slice has no storage");
                    return new ReadOnlySpan<byte>(source, checked((int)length)).ToArray();
                }
            }
            """;
    }
}

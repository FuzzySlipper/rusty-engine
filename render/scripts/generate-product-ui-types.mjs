// Writes the declarations a product UI compiles against, shipped by the C#
// SDK package as $(RustyEngineProductUiTypes):
//   @rusty-engine/product-ui  the mount signature and the context ports
//   @rusty-engine/live-debug  the optional debug panel the shell serves
// Each is tsc's declaration output for one entry module; the modules it
// reaches are renamed under the public name so none can collide with a
// product's own. `--check` fails when the checked-in file is stale.
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const render = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const target = path.resolve(render, '../csharp/Rusty.Engine/buildTransitive/rusty-engine-product-ui.d.ts');
const tsc = path.join(render, 'node_modules/.bin/tsc');

function declarations(entry, publicName, paths = {}) {
  const directory = mkdtempSync(path.join(tmpdir(), 'rusty-product-ui-types-'));
  try {
    const config = path.join(directory, 'tsconfig.json');
    writeFileSync(config, JSON.stringify({
      compilerOptions: {
        declaration: true,
        emitDeclarationOnly: true,
        module: 'amd',
        moduleResolution: 'node10',
        target: 'ES2022',
        lib: ['ES2022', 'DOM', 'DOM.Iterable'],
        strict: true,
        skipLibCheck: true,
        rootDir: path.join(render, 'packages'),
        outFile: path.join(directory, 'out.d.ts'),
        baseUrl: render,
        paths,
      },
      files: [path.join(render, entry)],
    }));
    execFileSync(tsc, ['-p', config], { stdio: 'inherit' });
    let text = readFileSync(path.join(directory, 'out.d.ts'), 'utf8');
    const entryName = path.relative(path.join(render, 'packages'), path.join(render, entry)).replace(/\.ts$/, '');
    for (const [, name] of text.matchAll(/^declare module "([^"]+)"/gm)) {
      text = text.replaceAll(`"${name}"`, `"${name === entryName ? publicName : `${publicName}/internal/${name}`}"`);
    }
    return text.trimEnd();
  } finally {
    rmSync(directory, { recursive: true, force: true });
  }
}

const generated = [
  '// Generated by render/scripts/generate-product-ui-types.mjs from the Engine\'s',
  '// browser sources; do not edit. Pass this file to a product UI\'s tsc to',
  '// type `@rusty-engine/product-ui` and `@rusty-engine/live-debug`.',
  declarations('packages/application-host/src/product-ui.ts', '@rusty-engine/product-ui'),
  declarations('packages/live-debug-panel/src/browser-mount.ts', '@rusty-engine/live-debug', {
    '@rusty-engine/live-debug-client': ['packages/live-debug-client/src/index.ts'],
  }),
  '',
].join('\n');

if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(target, 'utf8'); } catch { /* missing is stale */ }
  if (current !== generated) {
    console.error(`${path.relative(process.cwd(), target)} is stale: run node render/scripts/generate-product-ui-types.mjs`);
    process.exit(1);
  }
} else {
  writeFileSync(target, generated);
  console.log(`wrote ${path.relative(process.cwd(), target)}`);
}
